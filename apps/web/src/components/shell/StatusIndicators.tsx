"use client";
import type { ProcessingState, SourceMode } from "@echospace/schemas";
import { Badge, type Tone } from "@/components/ui/badge";
import { Tip } from "@/components/ui/tooltip";

const SOURCE: Record<SourceMode, { label: string; tone: Tone; help: string }> = {
  synthetic: { label: "Synthetic simulation", tone: "signal", help: "All observations are generated by the deterministic simulator. Nothing shown is a physical measurement." },
  recorded: { label: "Recorded data", tone: "geometry", help: "Replaying an imported recording. Values are measured by the original capture device; no ground truth is available." },
  hardware: { label: "Physical hardware", tone: "warn", help: "Live data from a connected acquisition device. Capture is visible and must be authorised." },
};

export function SourceBadge({ mode }: { mode: SourceMode }) {
  const s = SOURCE[mode];
  return (
    <Tip content={s.help}>
      <span data-testid="source-badge">
        <Badge tone={s.tone} dot>
          {s.label}
        </Badge>
      </span>
    </Tip>
  );
}

const STATE: Record<ProcessingState, { tone: Tone; label: string }> = {
  idle: { tone: "neutral", label: "Idle" },
  initializing: { tone: "neutral", label: "Initializing" },
  calibrating: { tone: "warn", label: "Calibrating" },
  streaming: { tone: "ok", label: "Streaming" },
  paused: { tone: "neutral", label: "Paused" },
  degraded: { tone: "warn", label: "Degraded" },
  error: { tone: "err", label: "Error" },
};

export function StateBadge({ state, stale }: { state: ProcessingState; stale?: boolean }) {
  const s = STATE[state];
  if (stale) return <Badge tone="warn">Stale · no new frames</Badge>;
  return (
    <span data-testid="state-badge">
      <Badge tone={s.tone} dot>
        {s.label}
      </Badge>
    </span>
  );
}
