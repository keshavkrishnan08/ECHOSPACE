"""Scenario presets A-J, exported from the TypeScript scenario builders.

The JSON files under ``presets/`` are generated by ``packages/engine/scripts/export-presets.ts``;
regenerate them rather than editing by hand.
"""

from __future__ import annotations

import json
from functools import cache
from importlib import resources
from typing import Any

from .config import ScenarioConfig


def _files() -> dict[str, Any]:
    root = resources.files(__package__).joinpath("presets")
    return {p.name.removesuffix(".json"): p for p in root.iterdir() if p.name.endswith(".json")}


@cache
def _raw(key: str) -> dict[str, Any]:
    files = _files()
    if key not in files:
        raise KeyError(f"unknown preset {key!r}; available: {', '.join(sorted(files))}")
    data: dict[str, Any] = json.loads(files[key].read_text(encoding="utf-8"))
    return data


def list_presets() -> list[dict[str, str]]:
    """Key, title, objective, lesson and difficulty of every preset, ordered by key."""
    out = []
    for key in sorted(_files()):
        raw = _raw(key)
        out.append({k: raw[k] for k in ("key", "title", "objective", "lesson", "difficulty")})
    return out


def load_preset(key: str) -> ScenarioConfig:
    """Validated configuration of preset `key` (a fresh copy on every call)."""
    return ScenarioConfig.model_validate(_raw(key)["config"])
